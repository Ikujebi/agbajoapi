import { emailHeader } from './email-header.template';
import { emailFooter } from './email-footer.template';

export interface BaseEmailBranding {
  /**
   * Organisation or platform name.
   */
  name?: string;

  /**
   * Public HTTPS logo URL.
   * Cloudinary URLs are recommended.
   */
  logoUrl?: string | null;

  /**
   * Public website URL.
   */
  websiteUrl?: string;

  /**
   * Main brand colour.
   */
  primaryColor?: string;

  /**
   * Secondary brand colour.
   */
  secondaryColor?: string;

  /**
   * Email header background.
   */
  headerBackground?: string;

  /**
   * Alternative text for the logo.
   */
  logoAlt?: string;
}

export interface BaseEmailLayoutOptions {
  title?: string;
  preheader?: string;
  content: string;
  footerText?: string;
  unsubscribeUrl?: string;

  /**
   * Optional organisation-specific branding.
   *
   * If omitted, AdugboHub branding is used.
   */
  branding?: BaseEmailBranding;

  /**
   * Convenience overrides.
   * These take precedence over branding properties.
   */
  logoUrl?: string | null;
  brandName?: string;
  websiteUrl?: string;
}

const DEFAULT_BRANDING = {
  name: 'AdugboHub',

  logoUrl:
    'https://res.cloudinary.com/wndv1ma4/image/upload/v1793890904/logo-purple.png',

  websiteUrl: 'https://adugbohub.com',

  primaryColor: '#D92D45',

  secondaryColor: '#7137A8',

  headerBackground: '#190021',

  logoAlt: 'AdugboHub - Neighbourhood App',
};

const BRAND = {
  background: '#F5F6FA',
  text: '#252238',
  muted: '#777487',
  border: '#E9E7EF',
};

/**
 * Escape dynamic text before inserting it into HTML.
 */
export function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/g, (character) => {
    const entities: Record<string, string> = {
      '&': '&amp;',
      '<': '&lt;',
      '>': '&gt;',
      '"': '&quot;',
      "'": '&#39;',
    };

    return entities[character];
  });
}

/**
 * Accept HTTPS URLs only.
 *
 * This prevents unsafe protocols such as javascript:
 * from being inserted into email links or image sources.
 */
function safeUrl(value?: string | null): string {
  if (!value || typeof value !== 'string') {
    return '';
  }

  try {
    const url = new URL(value.trim());

    if (url.protocol !== 'https:') {
      return '';
    }

    return url.toString();
  } catch {
    return '';
  }
}

/**
 * Only allow standard six-digit hexadecimal colours.
 */
function safeColor(
  value: string | undefined,
  fallback: string,
): string {
  if (!value) {
    return fallback;
  }

  const normalized = value.trim();

  return /^#[0-9A-Fa-f]{6}$/.test(normalized)
    ? normalized
    : fallback;
}

/**
 * Shared AdugboHub / organisation email layout.
 *
 * Supports platform-wide and organisation-specific branding.
 *
 * IMPORTANT:
 * `content` must contain HTML generated by trusted templates.
 * Escape all dynamic user-provided values before inserting them.
 */
export function baseEmailLayout(
  options: BaseEmailLayoutOptions,
): string {
  const {
    title = 'Your neighborhood, better connected',
    preheader = '',
    content,
    footerText,
    unsubscribeUrl,
    branding = {},
    logoUrl,
    brandName,
    websiteUrl,
  } = options;

  /**
   * Resolve branding.
   *
   * Priority:
   * 1. Explicit top-level option.
   * 2. Organisation branding.
   * 3. AdugboHub defaults.
   */
  const resolvedName =
    brandName?.trim() ||
    branding.name?.trim() ||
    DEFAULT_BRANDING.name;

  const resolvedLogo =
    logoUrl !== undefined
      ? logoUrl
      : branding.logoUrl !== undefined
        ? branding.logoUrl
        : process.env.MAIL_LOGO_URL || DEFAULT_BRANDING.logoUrl;

  const resolvedWebsite =
    websiteUrl ||
    branding.websiteUrl ||
    DEFAULT_BRANDING.websiteUrl;

  const resolvedPrimaryColor = safeColor(
    branding.primaryColor,
    DEFAULT_BRANDING.primaryColor,
  );

  const resolvedSecondaryColor = safeColor(
    branding.secondaryColor,
    DEFAULT_BRANDING.secondaryColor,
  );

  const resolvedHeaderBackground = safeColor(
    branding.headerBackground,
    DEFAULT_BRANDING.headerBackground,
  );

  const safeTitle = escapeHtml(title);
  const safePreheader = escapeHtml(preheader);

  /**
   * Preserve the default logo if an organisation does not
   * provide a valid HTTPS logo URL.
   *
   * An explicit null or invalid URL therefore falls back
   * to the AdugboHub logo.
   */
  const resolvedLogoUrl =
    safeUrl(resolvedLogo) || DEFAULT_BRANDING.logoUrl;

  /**
   * Header component.
   */
  const header = emailHeader({
    brandName: resolvedName,
    logoUrl: resolvedLogoUrl,
    websiteUrl: safeUrl(resolvedWebsite),
    primaryColor: resolvedPrimaryColor,
    headerBackground: resolvedHeaderBackground,
    logoAlt: branding.logoAlt || DEFAULT_BRANDING.logoAlt,
  });

  /**
   * Footer component.
   */
  const footer = emailFooter({
    brandName: resolvedName,
    footerText:
      footerText ||
      `You are receiving this email because you have an account or relationship with ${resolvedName}.`,
    unsubscribeUrl,
    websiteUrl: resolvedWebsite,
    secondaryColor: resolvedSecondaryColor,
    mutedColor: BRAND.muted,
    borderColor: BRAND.border,
    poweredByText: 'Powered by AdugboHub',
  });

  return `
<!DOCTYPE html>
<html lang="en">

<head>
  <meta charset="UTF-8">

  <meta
    name="viewport"
    content="width=device-width, initial-scale=1"
  >

  <meta name="color-scheme" content="light">

  <meta
    name="supported-color-schemes"
    content="light"
  >

  <title>${safeTitle}</title>
</head>

<body style="
  margin:0;
  padding:0;
  background:${BRAND.background};
  font-family:Arial,Helvetica,sans-serif;
  color:${BRAND.text};
">

  <!-- Preheader -->
  <div style="
    display:none;
    max-height:0;
    overflow:hidden;
    opacity:0;
    color:transparent;
    visibility:hidden;
    mso-hide:all;
  ">
    ${safePreheader}
  </div>

  <!-- Main email background -->
  <table
    role="presentation"
    width="100%"
    cellpadding="0"
    cellspacing="0"
    border="0"
    style="
      width:100%;
      background:${BRAND.background};
      border-collapse:collapse;
    "
  >

    <tr>
      <td
        align="center"
        style="padding:32px 16px;"
      >

        <!-- Email container -->
        <table
          role="presentation"
          width="100%"
          cellpadding="0"
          cellspacing="0"
          border="0"
          style="
            width:100%;
            max-width:600px;
            background:#FFFFFF;
            border-radius:16px;
            overflow:hidden;
            border:1px solid ${BRAND.border};
            border-collapse:separate;
          "
        >

          <!-- Reusable email header -->
          ${header}

          <!-- Email content -->
          <tr>
            <td style="
              padding:36px 32px;
              font-size:15px;
              line-height:1.7;
              color:${BRAND.text};
            ">
              ${content}
            </td>
          </tr>

          <!-- Reusable email footer -->
          ${footer}

        </table>
        <!-- End email container -->

      </td>
    </tr>

  </table>

</body>
</html>
  `.trim();
}